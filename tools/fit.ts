/**
 * Offline contact fitting: for every key marked `fit` in poses.ts, nudges the
 * listed freedoms (root, torso, whole-body tilt ...) so each planted hand/foot
 * actually reaches its spot, and writes the result to src/anim/fitted.ts.
 *   npx esbuild tools/fit.ts --bundle --platform=node --outfile=/tmp/fit.cjs && node /tmp/fit.cjs
 */
import { writeFileSync } from 'node:fs';
import { ANIMS } from '../src/anim/poses';
import { buildKeys } from '../src/anim/sampler';
import type { Pose } from '../src/anim/types';
const fitted: Record<string, Record<number, Partial<Pose>>> = {};
for (const k of Object.keys(ANIMS)) {
  if (!ANIMS[k].frames.some((f) => f.fit)) continue;
  const keys = buildKeys(k, true, fitted);
  const worst = Math.max(0, ...keys.flatMap((q) => Object.values(q.miss ?? {})));
  console.log(k.padEnd(18), 'fitted keys', Object.keys(fitted[k] ?? {}).length, 'worst miss', (worst * 14.8).toFixed(1), 'cm');
}
const src = `import type { Pose } from './types';\n\n/** Offline contact fits for keys marked \`fit\` (GENERATED by tools/fit.ts — do not edit by hand). */\nexport const FITTED: Record<string, Record<number, Partial<Pose>>> = ${JSON.stringify(fitted, null, 1)};\n`;
writeFileSync('src/anim/fitted.ts', src);
